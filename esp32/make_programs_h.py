"""Writes esp32/chip_test/programs.h: engine programs assembled by model/asm.py, so the ESP32 loads exactly
what the simulations tested. Run after changing any program:  python esp32/make_programs_h.py"""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "model"))
from asm import assemble
out = ["// Generated by esp32/make_programs_h.py from programs/*.asm. Do not edit by hand.", "#pragma once", "#include <stdint.h>"]
NAMES = ("uart_tx", "uart_rx", "measure_baud", "measure_pulse", "measure_high", "read_pins", "push_789", "i2c_master", "i2c_sniff", "spi_master", "keypad", "ir_nec", "ir_tx", "dali_tx", "dali_rx", "eth_tx", "ser_tx", "onewire", "lcd1602")
py = ["# Generated by esp32/make_programs_h.py from programs/*.asm. Do not edit by hand.",
      "# name -> (words, wrap_bottom, wrap_top), for the MicroPython host in pico/", "PROGRAMS = {"]
labels_py = []
for name in NAMES:
    p = assemble(open(os.path.join(ROOT, "programs", name + ".asm")).read())
    words = ", ".join(f"0x{w:04X}" for w in p.words)
    out.append(f"const uint16_t PROG_{name.upper()}[] = {{{words}}};")
    out.append(f"const int PROG_{name.upper()}_LEN = {len(p.words)}, PROG_{name.upper()}_WRAP_BOTTOM = {p.wrap_bottom}, PROG_{name.upper()}_WRAP_TOP = {p.wrap_top};")
    for lab, addr in sorted(p.labels.items(), key=lambda kv: kv[1]):
        out.append(f"const int {name.upper()}_{lab.upper()} = {addr};")
    py.append(f'    "{name}": ([{words}], {p.wrap_bottom}, {p.wrap_top}),')
    labels_py.append(f'    "{name}": {{{", ".join(f"{chr(34)}{lab}{chr(34)}: {addr}" for lab, addr in sorted(p.labels.items(), key=lambda kv: kv[1]))}}},')
py.append("}")
py.append("# name -> {label: address}: the routine numbers a host puts in a command word (i2c_master: xfer, start, stop)")
py.append("LABELS = {")
py.extend(labels_py)
py.append("}")
os.makedirs(os.path.join(ROOT, "pico"), exist_ok=True)
open(os.path.join(ROOT, "pico", "programs.py"), "w").write("\n".join(py) + "\n")
open(os.path.join(ROOT, "esp32", "chip_test", "programs.h"), "w").write("\n".join(out) + "\n")
print("\n".join(out[3:]))
